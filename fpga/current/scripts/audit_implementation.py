"""Recheck CE proof against the netlist actually passed to P&R.

The implementation command reruns synthesis. Do not assume its netlist is
identical to the standalone synthesis used to generate the applied SDC.
This script writes evidence only; it never changes the applied constraints.
"""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

root = Path(__file__).resolve().parents[1]
build = Path('E:/Gowin/workspace') / root.name
archive = root.parents[1] / 'artifacts' / root.name
command = (build / 'impl/pnr/cmd.do').read_text()
assert re.search(r'(?m)^-place_option 3\s*$', command)
assert re.search(r'(?m)^-route_option 2\s*$', command)
netlist = Path(re.search(r'(?m)^-d (.+)$', command)[1].strip())
assert netlist.resolve().is_relative_to(build.resolve())
fresh_json = archive / 'pnr_half_rate_audit.json'
fresh_sdc = archive / 'pnr_half_rate_enumerated.sdc'
subprocess.run([
    sys.executable, str(root / 'scripts/audit_half_rate.py'),
    '--netlist', str(netlist), '--contest-strings',
    '--omit-patterns', str(root / 'scripts/retained_constraint_omissions.json'),
    '--output', str(fresh_json), '--sdc', str(fresh_sdc),
], check=True)
initial = json.loads((archive / 'half_rate_audit.json').read_text())
actual = json.loads(fresh_json.read_text())
keys = ('patterns', 'half_rate_ffs', 'single_cycle_ffs',
        'manual_launch_patterns', 'primitive_scopes',
        'independent_phases', 'independent_envelopes',
        'independent_voice_instances')
comparisons = {key: initial[key] == actual[key] for key in keys}
strip_hash = lambda text: re.sub(
    r'(?m)^# Generated by audit_half_rate.py from netlist SHA256 .*$',
    '# Generated by audit_half_rate.py', text)
same_sdc = strip_hash(fresh_sdc.read_text()) == strip_hash(
    (root / 'constraints/half_rate_enumerated.sdc').read_text())
result = dict(implementation_netlist=str(netlist),
              implementation_netlist_sha256=actual['netlist_sha256'],
              initial_netlist_sha256=initial['netlist_sha256'],
              netlist_text_equal=initial['netlist_sha256'] == actual['netlist_sha256'],
              comparisons=comparisons,
              regenerated_sdc_equal_except_netlist_hash_comment=same_sdc)
(archive / 'resynthesis_equivalence.json').write_text(json.dumps(result, indent=2))
print(json.dumps(result, indent=2))
assert all(comparisons.values()) and same_sdc, 'Implementation proof changed: review before acceptance'
subprocess.run([sys.executable, str(root / 'scripts/compact_queries.py'),
                '--verify-netlist', str(netlist)], check=True)
applied = build / 'constraints/v3_hdmi.sdc'
assert applied.read_bytes() == (root / 'constraints/v3_hdmi.sdc').read_bytes()
print('Actual implementation netlist and applied SDC independently verified; SHA256',
      hashlib.sha256(applied.read_bytes()).hexdigest())
