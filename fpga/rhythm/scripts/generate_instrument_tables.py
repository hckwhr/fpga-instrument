"""Reproducible, original harmonic presets; no recorded samples or soundfonts.

Only the table data are generated. Existing piano data remain bit-exact and
the synthesizer keeps its shared interpolation pipeline and 32 voice states.
"""
from pathlib import Path
import math
import re

ROOT = Path(__file__).resolve().parents[1]
HARMONICS = (
    (1.0, .09, .025, .01),                       # flute: almost sinusoidal
    (1.0, .025, .42, .01, .18, .005, .06),       # clarinet: odd partials
    (1.0, .5, .18, .32, .06, .09, 0.0, .12),   # organ: octave registrations
)


def make_banks():
    source = (ROOT / 'rtl/piano_wave.vh').read_text(encoding='utf-8')
    matches = re.findall(r"7'd(\d+): piano_point = (-?)16'sd(\d+);", source)
    piano = [0] * 128
    assert len(matches) == 128
    for index, sign, value in matches:
        piano[int(index)] = int(value) * (-1 if sign else 1)
    banks = [piano]
    for partials in HARMONICS:
        raw = [sum(gain * math.sin(2 * math.pi * h * i / 128)
                   for h, gain in enumerate(partials, 1)) for i in range(128)]
        scale = max(abs(x) for x in piano) / max(abs(x) for x in raw)
        banks.append([round(x * scale) for x in raw])
    return banks


def generate_tables():
    rows = ['// Generated by scripts/generate_instrument_tables.py.',
            '// 512 x 33 bits: {signed point[15:0], signed delta[16:0]}.',
            '// 0 piano, 1 synthetic flute, 2 synthetic clarinet, 3 synthetic organ.',
            'initial begin']
    for bank, points in enumerate(make_banks()):
        for index, point in enumerate(points):
            delta = points[(index + 1) % 128] - point
            packed = ((point & 0xffff) << 17) | (delta & 0x1ffff)
            rows.append(f"    points[{bank * 128 + index}] = 33'h{packed:09x};")
    rows.extend(['end', ''])
    (ROOT / 'rtl/instrument_timbre_rom_init.vh').write_text('\n'.join(rows), encoding='utf-8')


def generate_labels():
    # Append to unused slots; every old glyph/address stays unchanged.
    # Font generation is optional on non-Windows hosts: checked-in bits suffice.
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype('C:/Windows/Fonts/msyhbd.ttc', 24)
    target = ROOT / 'rtl/chinese_font_rom_init.vh'
    text = target.read_text(encoding='utf-8')
    for glyph, char in enumerate('长笛单簧管风形灵乐器', 137):
        image = Image.new('1', (24, 24))
        draw = ImageDraw.Draw(image)
        left, top, right, bottom = draw.textbbox((0, 0), char, font=font)
        draw.text(((24-(right-left))//2-left, (24-(bottom-top))//2-top), char, font=font, fill=1)
        for row in range(32):
            bits = ''.join('1' if row < 24 and image.getpixel((x, row)) else '0' for x in range(24))
            address = glyph * 32 + row
            text, count = re.subn(rf"font_memory\[{address}\] = 24'b[01]{{24}};",
                                 f"font_memory[{address}] = 24'b{bits};", text)
            assert count == 1, address
    target.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--fonts', action='store_true')
    args = parser.parse_args()
    generate_tables()
    if args.fonts:
        generate_labels()
